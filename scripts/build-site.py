#!/usr/bin/env python3
"""Pack the character art for the landing page (site/).

Writes site/hush-data.js: window.HUSH_DATA with every pose and expression per body, the round-eyed rig per body
(toppers and wearables live there), the palettes, and the wearable → rig layers map read from
Sources/HushCore/Wardrobe.swift, so the page dresses Hush exactly like the app does.

Run after changing assets/character or the wardrobe:  python3 scripts/build-site.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CHAR = ROOT / "assets/character"
BODIES = ["blob", "bean", "square"]


def svgs(folder: pathlib.Path) -> dict:
    return {p.stem: p.read_text(encoding="utf-8") for p in sorted(folder.glob("*.svg"))}


def wardrobe() -> dict:
    src = (ROOT / "Sources/HushCore/Wardrobe.swift").read_text(encoding="utf-8")
    pieces = {}
    for m in re.finditer(r'\.init\(id: "(\w+)".*?slot: \.(\w+).*?layers: \[([^\]]*)\]\)', src):
        pieces[m.group(1)] = {"slot": m.group(2), "layers": re.findall(r'"([\w-]+)"', m.group(3))}
    return pieces


data = {
    "poses": {b: svgs(CHAR / "poses" / b) for b in BODIES},
    "expressions": {b: svgs(CHAR / "expressions" / b) for b in BODIES},
    "rigs": {b: (CHAR / f"rig/hush-rig-{b}-round.svg").read_text(encoding="utf-8") for b in BODIES},
    "palettes": json.loads((CHAR / "palettes.json").read_text(encoding="utf-8")),
    "wear": wardrobe(),
}
assert len(data["wear"]) == 45, f"expected 45 wearables, read {len(data['wear'])}"

out = ROOT / "site/hush-data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("// Generated by scripts/build-site.py from assets/character. Don't edit.\nwindow.HUSH_DATA = "
               + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB, {len(data['wear'])} wearables)")
