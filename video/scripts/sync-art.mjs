// Pulls the art the videos use from the repo (never edited here): the fonts the website uses, and the edge flags.
// The character itself comes straight from site/hush-data.js + site/hush.js (see src/lib/Hush.tsx).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
mkdirSync(join(here, "..", "public", "fonts"), { recursive: true });
for (const f of readdirSync(join(repo, "site", "fonts")).filter((f) => f.endsWith(".woff2"))) {
  copyFileSync(join(repo, "site", "fonts", f), join(here, "..", "public", "fonts", f));
}
const edge = {};
for (const f of readdirSync(join(repo, "assets", "character", "edge")).filter((f) => f.endsWith(".svg"))) {
  edge[f.replace(/\.svg$/, "")] = readFileSync(join(repo, "assets", "character", "edge", f), "utf8");
}
mkdirSync(join(here, "..", "src", "generated"), { recursive: true });
writeFileSync(join(here, "..", "src", "generated", "edge.ts"),
  "// Generated by scripts/sync-art.mjs from assets/character/edge. Don't edit.\nexport const EDGE: Record<string, string> = " +
  JSON.stringify(edge) + ";\n");
console.log(`synced fonts and ${Object.keys(edge).length} edge pieces`);

// The icons of the apps Hush works with, from this Mac (macOS only; they stay out of git).
if (process.platform === "darwin") {
  const { spawnSync } = await import("node:child_process");
  spawnSync("swift", [join(here, "app-icons.swift"), join(here, "..", "public", "logos")], { stdio: "inherit" });
}
